"""tools/catalog.py -> src/Catalog.cs (product data and RU/EN texts).
python3 gen_cs.py <src_dir>"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalog import ALL, FX

KG = {'tin_tea': .015, 'tin_tall': .015, 'tin_low': .015, 'tin_coffee': .02, 'box_bags': .01, 'box_tall': .015, 'box_flat': .015, 'box_sticks': .02,
      'pack_paper': .02, 'bag_valve': .02, 'sachet': .03, 'brick': .02, 'cake': .03, 'jar': .02, 'can': .3}


GRAMS = {'cake': 357, 'cake_small': 100, 'tuocha': 100, 'tuo_mini': 5, 'mushroom': 250, 'melon': 500, 'ball': 8, 'tangerine': 10, 'coin': 7, 'brick_tea': 250, 'tile': 250,
         'square': 200, 'square_mini': 9, 'briquette': 100, 'log': 725, 'bamboo': 100, 'basket': 250, 'sack': 300, 'tablet': 90, 'can_short': 250, 'can_wide': 380, 'bottle': 300}


def kg(p):
    m = p['model']
    if m in KG: return KG[m]
    if m in GRAMS: return round(max(.005, GRAMS[m] / 1000 / p['servings']), 3)
    return .02


def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def fx_ru(p):
    """effects are shown as icons in the game (owner 11-15: no effect text); only how it is drunk stays in words"""
    return 'Пьётся холодным, огонь не нужен.' if p.get('cold') and 'огн' not in p['d_ru'] and 'огон' not in p['d_ru'] else ''


def fx_en(p):
    return 'Drunk cold, no fire needed.' if p.get('cold') and 'fire' not in p['d_en'] else ''


lines = ['namespace TeaCoffeeByEMPEROR;', '',
         '/// <summary>Generated by tools/gen_cs.py from tools/catalog.py: the products and their texts.</summary>',
         'public static class Catalog', '{',
         '    public sealed record P(string Id, bool Tea, string Model, int Servings, float Kg, string? Cup, float Warm, float WarmHours, float Awake, bool Rest, bool Heal,',
         '        float Kcal, float Thirst, bool Cold, int Loot, string? CupTex, string Fx, int Liquid);', '',
         '    public sealed record F(string Key, bool Good, float Hours, string Ru, string En, string RuD, string EnD);', '',
         '    public static readonly F[] Fx =', '    {'] + [f'        new({q(k)}, {str(v[0]).lower()}, {v[1]}f, {q(v[2])}, {q(v[3])}, {q(v[4])}, {q(v[5])}),' for k, v in FX.items()] + ['    };', '',
         '    public static readonly P[] All =', '    {']
for p in ALL:
    cup = q(p['cup']) if p.get('cup') else 'null'
    lines.append(f'        new({q(p["id"])}, {str(p["kind"] == "tea").lower()}, {q(p["model"])}, {p["servings"]}, {kg(p)}f, {cup}, {p.get("warm", 0)}f, {p.get("warm_hours", 0)}f, '
                 f'{p.get("awake", 0)}f, {str(bool(p.get("rest"))).lower()}, {str(bool(p.get("heal"))).lower()}, {p["kcal"]}f, {p["thirst"]}f, {str(bool(p.get("cold"))).lower()}, {p["loot"]}, {q(p["cuptex"]) if p.get("cuptex") else "null"}, {q(" ".join(p["fx"]))}, 0x{p["liquid"][0]:02X}{p["liquid"][1]:02X}{p["liquid"][2]:02X}),')
lines += ['    };', '', '    public static readonly (string Key, string Ru, string En)[] Texts =', '    {']
for p in ALL:
    i = p['id']
    if p.get('cup'):
        brew_ru = 'Заваривается на огне: положи в котелок или кастрюлю с водой.' if p['kind'] == 'tea' else 'Готовится на огне: положи в котелок или кастрюлю с водой.'
        if p['servings'] == 1: brew_ru += ' Хватает на один раз.'
        else: brew_ru += f' Порций: {p["servings"]}.'
        brew_en = 'Brew it over a fire: put it in a pot with water.' + (' Enough for one cup.' if p['servings'] == 1 else f' Servings: {p["servings"]}.')
        lines.append(f'        ({q(i + "_NAME")}, {q(p["ru"] + " (" + p["sort_ru"] + ")")}, {q(p["en"] + " (" + p["sort_en"] + ")")}),')
        lines.append(f'        ({q(i + "_DESC")}, {q((p["d_ru"] + " " + brew_ru + " " + fx_ru(p)).strip())}, {q((p["d_en"] + " " + brew_en + " " + fx_en(p)).strip())}),')
        cup_ru = ('Стакан чая' if p['kind'] == 'tea' else 'Кружка кофе') + ' «' + p['ru'] + '»'
        cup_en = ('A glass of ' if p['kind'] == 'tea' else 'A mug of ') + p['en'] + (' tea' if p['kind'] == 'tea' and 'tea' not in p['en'].lower() else '')
        if p['id'] in ('BlueBlossom',): cup_ru, cup_en = 'Кружка цикория «Синий цветок»', 'A mug of Blue Blossom chicory'
        if True:
            v_ru, v_en = {'glass': ('Стакан', 'Glass'), 'mug': ('Кружка', 'Mug'), 'piala': ('Пиала', 'Bowl'), 'ceramic': ('Чашка', 'Cup'), 'espresso': ('Чашечка', 'Espresso cup'), 'camp': ('Походная кружка', 'Camp mug'), 'yunomi': ('Юноми', 'Yunomi')}[p['cup']]
            # owner 11-15: no vessel word in a drink's name (the cup shows what it is)
            cup_ru = f"{p['ru']} ({p['sort_ru']})"; cup_en = f"{p['en']} ({p['sort_en']})"
        lines.append(f'        ({q(i + "Cup_NAME")}, {q(cup_ru)}, {q(cup_en)}),')
        lines.append(f'        ({q(i + "Cup_DESC")}, {q((p["d_ru"] + " " + fx_ru(p)).strip())}, {q((p["d_en"] + " " + fx_en(p)).strip())}),')
    else:
        lines.append(f'        ({q(i + "_NAME")}, {q(p["ru"] + " (" + p["sort_ru"] + ")")}, {q(p["en"] + " (" + p["sort_en"] + ")")}),')
        lines.append(f'        ({q(i + "_DESC")}, {q((p["d_ru"] + " " + fx_ru(p)).strip())}, {q((p["d_en"] + " " + fx_en(p)).strip())}),')
lines += ['    };', '}', '']
open(os.path.join(sys.argv[1], 'Catalog.cs'), 'w').write('\n'.join(lines))
print('Catalog.cs:', len(ALL), 'products')
