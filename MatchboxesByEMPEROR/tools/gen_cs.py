"""Writes src/Catalog.cs from catalog.py: kinds, series and labels with their RU/EN names."""
import os
from catalog import KINDS, SERIES, labels
from memes import MEMES

HERE = os.path.dirname(os.path.abspath(__file__))


def s(x):
    return '"' + x.replace('\\', '\\\\').replace('"', '\\"') + '"'


out = ['// generated by tools/gen_cs.py from tools/catalog.py: do not edit by hand', 'namespace MatchboxesByEMPEROR;', '',
       'public static partial class Catalog', '{', '    public static readonly KindDef[] Kinds =', '    {']
for k, (ru, en, base, n, (L, W, H), w) in KINDS.items():
    out.append(f'        new({s(k)}, {s(ru)}, {s(en)}, {s(base)}, {n}, {w}),')
out += ['    };', '', '    public static readonly SeriesDef[] Series =', '    {']
for key, kind, layout, sru, sen, rows in SERIES:
    out.append(f'        new({s(key)}, {s(kind)}, {s(sru)}, {s(sen)}, {len(rows)}),')
out += ['    };', '', '    public static readonly LabelDef[] Labels =', '    {']
for l in labels():
    out.append(f'        new({s(l["id"])}, {s(l["series"])}, {s(l["kind"])}, {l["n"]}, {s(l["ru"])}, {s(l["en"])}),')
out += ['    };', '', '    /// <summary>One joke line per label: Russian, English.</summary>', '    public static readonly Dictionary<string, (string Ru, string En)> Memes = new()', '    {']
for key, kind, layout, sru, sen, rows in SERIES:
    for r in rows:
        m = MEMES[key][r[0]]
        out.append(f'        [{s(key + "_" + r[0])}] = ({s(m[0])}, {s(m[1])}),')
out += ['    };', '}', '']
open(os.path.join(HERE, '..', 'src', 'Catalog.cs'), 'w', encoding='utf-8').write('\n'.join(out))
print('Catalog.cs:', len(labels()), 'labels')
