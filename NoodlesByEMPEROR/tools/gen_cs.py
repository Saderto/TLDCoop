"""Writes ../src/Catalog.g.cs from catalog.py."""
import os
from catalog import NOODLES
from memes import MEME
HERE = os.path.dirname(os.path.abspath(__file__))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def f(x): return f'{x}f'
rows = []
import catalog as C
BIG = ('big', 'bigcup', 'bucket', 'kbowl', 'box', 'ufo')
CHEM = ('HonestPrice', 'BabyStar', 'MamyMonster')


def fx(s):
    """Effects of the brewed one (src/Effects.cs): brothreserve appetite | emptycal heartburn tears.
    None of them may repeat an effect the game or our other mods already have (user rule 11-14): warmth and thirst stay plain item values."""
    r = []
    low = s['ruf'].lower()
    rich = s['broth'] in (C.TONK, C.BF, C.MISO) or any(k in low for k in ('костн', 'тонкоцу', 'говя', 'свиной бульон', 'навари', 'мисо')) or 'cheese' in s['top'] or 'shrimp' in s['top'] or 'nori' in s['top']
    if not s['dry'] and s['spicy'] <= 1: r.append('brothreserve')
    if rich and s['brand'] not in CHEM: r.append('appetite')
    if s['brand'] in CHEM: r.append('emptycal')
    if s['spicy'] >= 3: r.append('heartburn')
    if s['spicy'] >= 4: r.append('tears')
    return ' '.join(r)


for s in NOODLES:
    common = f'Shape = {q(s["shape"])}, Brand = {q(s["brand"])}, Kcal = {f(s["kcal"])}, Ru = {q(s["ru"])}, En = {q(s["en"])}, RuF = {q(s["ruf"])}, EnF = {q(s["enf"])}, Spicy = {s["spicy"]}, Dry = {"true" if s["dry"] else "false"}, Fx = {q(fx(s))}, Broth = {q(s["broth"])}'
    m = MEME[s['id']]
    rows.append(f'new Def {{ Id = {q(s["id"])}, Kind = Kind.Noodle, RuM = {q(m[0])}, EnM = {q(m[1])}, Mesh = {q(s["mesh"])}, Texture = {q(s["id"])}, Kg = {f(s["kg"])}, Water = {f(s["water"])}, {common} }},')
    rows.append(f'new Def {{ Id = {q(s["id"] + "Hot")}, Kind = Kind.Brewed, RuM = {q(m[2])}, EnM = {q(m[3])}, Raw = {q(s["id"])}, Mesh = {q(s["hotmesh"])}, Texture = {q(s["hottex"])}, Kg = {f(round(s["kg"] + s["water"] * (.25 if s["dry"] else .9), 3))}, Thirst = {f(s["thirst"])}, Warm = {f(round(s["warm"] * (.7 if s["brand"] in CHEM else 1), 2))}, {common} }},')
open(os.path.join(HERE, '..', 'src', 'Catalog.g.cs'), 'w').write(
    '// Generated by tools/gen_cs.py from tools/catalog.py: do not edit by hand.\nnamespace NoodlesByEMPEROR;\n\npublic static partial class Defs\n{\n    public static readonly Def[] All =\n    {\n'
    + '\n'.join('        ' + r for r in rows) + '\n    };\n}\n')
print(len(rows), 'defs')
