"""DESIGNS -> src/LighterTable.cs + data/text_lighter_{ru,en}.json"""
import os, re, json, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'lighter_designs.py'), encoding='utf-8').read()
rows = re.findall(r"\(\s*'(\w+)',\s*'([^']*)',\s*'([^']*)',\s*'(\w+)',\s*lambda.*?,\s*(\d)\),", src)
from bake_lighters_names import mesh_name
from lighter_memes import MEME
KIND = {  # fuel, charges, kg, fire bonus %, ru desc, en desc
 'zappo': ('petrol', 150, .06, 10, 'Бензиновая ветрозащитная зажигалка: огонь за решёткой колпачка держится на ветру.', 'A petrol windproof lighter: the flame behind the chimney holds in the wind.'),
 'imco': ('petrol', 120, .05, 10, 'Лёгкая бензиновая ветрозащитная зажигалка с колпачком.', 'A light petrol windproof lighter with a cap.'),
 'ronsan': ('petrol', 130, .08, 0, 'Бензиновая классика с рычагом: зажигается одним нажатием.', 'A petrol classic with a lever: lights with one press.'),
 'pipe': ('petrol', 100, .05, 5, 'Трубочная бензиновая зажигалка: пламя бьёт вбок, удобно раскуривать трубку.', 'A petrol pipe lighter: the flame leans sideways, made for lighting a pipe.'),
 'dupant': ('gas', 200, .09, 0, 'Дорогая газовая зажигалка с мягким жёлтым пламенем. Газа хватает надолго, но ветер её задувает.', 'An expensive gas lighter with a soft yellow flame. The gas lasts long, but the wind blows it out.'),
 'kolibri': ('gas', 180, .05, 15, 'Газовая турбо-зажигалка: синяя струя пламени почти не боится ветра.', 'A gas jet lighter: the blue torch flame hardly minds the wind.'),
}
FUEL = {'petrol': ('Топливо: бензин для зажигалок.', 'Fuel: lighter fluid.'), 'gas': ('Топливо: газ для зажигалок.', 'Fuel: lighter butane.')}
STARS = {1: '★☆☆', 2: '★★☆', 3: '★★★'}
ru, en = {}, {}
cs = []
for key, rn, enn, kind, rar in rows:
    rar = int(rar)
    if kind == 'refill':
        continue
    fuel, ch, kg, bonus, rd, ed = KIND[kind]
    ru[f'SMOKES_{key}_NAME'] = 'Зажигалка ' + rn if not rn.startswith('Трубочная') else rn.replace('Трубочная', 'Трубочная зажигалка')
    en[f'SMOKES_{key}_NAME'] = enn + ' Lighter' if 'Lighter' not in enn else enn
    ru[f'SMOKES_{key}_DESC'] = f'{rd} {FUEL[fuel][0]} Около {ch} зажиганий. Редкость {STARS[rar]}.'
    en[f'SMOKES_{key}_DESC'] = f'{ed} {FUEL[fuel][1]} About {ch} lights. Rarity {STARS[rar]}.'
    if key in MEME:
        ru[f'SMOKES_{key}_DESC'] += '\n\n«' + MEME[key][0] + '»'
        en[f'SMOKES_{key}_DESC'] += '\n\n“' + MEME[key][1] + '”'
    cs.append(f'        new("{key}", "{kind}", "{mesh_name(key)}", "{fuel}", {ch}, {kg}f, {bonus}f, {rar}),')
ru['SMOKES_LighterFluid_NAME'] = 'Бензин для зажигалок'
en['SMOKES_LighterFluid_NAME'] = 'Lighter Fluid'
ru['SMOKES_LighterFluid_DESC'] = 'Жестянка бензина для бензиновых зажигалок: Zappo, Imko, Ronsan и трубочных Old Boy. Хватит примерно на 600 зажиганий.'
en['SMOKES_LighterFluid_DESC'] = 'A tin of fluid for petrol lighters: Zappo, Imko, Ronsan and Old Boy pipe lighters. Enough for about 600 lights.'
ru['SMOKES_ButaneCan_NAME'] = 'Газ для зажигалок'
en['SMOKES_ButaneCan_NAME'] = 'Lighter Butane'
ru['SMOKES_ButaneCan_DESC'] = 'Баллончик очищенного газа для газовых зажигалок: Dupant и Kolibri. Хватит примерно на 900 зажиганий.'
en['SMOKES_ButaneCan_DESC'] = 'A can of refined butane for gas lighters: Dupant and Kolibri. Enough for about 900 lights.'
T = {
 'SMOKES_ACT_REFILL': ('Заправить', 'Refill'),
 'SMOKES_MSG_REFILLED': ('Заправлено: {0}, +{1} зар.', 'Refilled: {0}, +{1} lights'),
 'SMOKES_MSG_NO_LIGHTER_FUEL': ('Нет зажигалки, которую можно заправить этим топливом', 'No lighter that takes this fuel'),
 'SMOKES_MSG_LIGHTERS_FULL': ('Все подходящие зажигалки уже заправлены', 'All matching lighters are already full'),
 'SMOKES_MSG_NEW_LIGHTER': ('Новая зажигалка в коллекции: {0} из {1}', 'New lighter in the collection: {0} of {1}'),
 'SMOKES_UNIT_REFILL_ONE': ('заряд', 'light'),
 'SMOKES_UNIT_REFILL_MANY': ('зарядов', 'lights'),
 'SMOKES_UNIT_REFILL_SHORT': ('зар.', 'uses'),
 'SMOKES_COLL_LIGHTERS': ('Зажигалки', 'Lighters'),
 'SMOKES_COLL_LIGHTERS_DESC': ('Найденные коллекционные зажигалки', 'Collectible lighters found'),
 'SMOKES_COLL_UNKNOWN': ('???', '???'),
 'SMOKES_COLL_UNKNOWN_DESC': ('Эта зажигалка ещё не найдена.', 'This lighter has not been found yet.'),
 'SMOKES_COLL_BACK': ('Назад', 'Back'),
 'SMOKES_COLL_COUNT': ('Найдено {0} из {1}', 'Found {0} of {1}'),
}
for k, (r, e) in T.items():
    ru[k], en[k] = r, e
D = './dist/Mods/SmokesBySeagull/data'
json.dump(ru, open(os.path.join(D, 'text_lighter_ru.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
json.dump(en, open(os.path.join(D, 'text_lighter_en.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
open('./src/LighterTable.cs', 'w', encoding='utf-8').write(
'''namespace SmokesBySeagull;

/// <summary>Generated by tools/gen_lighters_cs.py from tools/lighter_designs.py: the collectible lighters in collection order.</summary>
public static partial class Lighters
{
    public record Design(string Id, string Kind, string Mesh, string Fuel, int Charges, float Kg, float FireBonus, int Rarity);

    public static readonly Design[] All =
    {
''' + '\n'.join(cs) + '''
    };
}
''')
print(len(cs), 'lighters')
